//! Crash-resumable, standalone-only import of legacy shared registries.
use crate::{BrokerError, FlowProfileRegistry, GroupRegistry, SubscriptionRegistry};
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

#[derive(Serialize, Deserialize)]
struct Import {
    sources: Vec<PathBuf>,
    suffix: String,
    copied: bool,
}

#[derive(Deserialize)]
struct Tombstones {
    #[serde(default)]
    tombstones: Vec<Tombstone>,
}
#[derive(Deserialize)]
struct Tombstone {
    id: uuid::Uuid,
}
fn deleted(path: &Path) -> Result<std::collections::HashSet<uuid::Uuid>, BrokerError> {
    match std::fs::read(path) {
        Ok(bytes) => Ok(serde_json::from_slice::<Tombstones>(&bytes)
            .map_err(error)?
            .tombstones
            .into_iter()
            .map(|t| t.id)
            .collect()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Default::default()),
        Err(e) => Err(error(e)),
    }
}

fn error(error: impl std::fmt::Display) -> BrokerError {
    BrokerError::InvalidConfig(format!("legacy catalog import: {error}"))
}

pub(crate) fn import(
    dir: &Path,
    flows: &FlowProfileRegistry,
    queues: &SubscriptionRegistry,
    groups: &GroupRegistry,
) -> Result<(), BrokerError> {
    let marker = dir.join("catalog-import.json");
    let pending = match std::fs::read(&marker) {
        Ok(bytes) => Some(serde_json::from_slice::<Import>(&bytes).map_err(error)?),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(error(e)),
    };
    const NAMES: [&str; 4] = [
        "flows.json",
        "subscriptions.json",
        "groups.json",
        "catalog-tombstones.json",
    ];
    let sources = if let Some(pending) = &pending {
        if !pending
            .suffix
            .strip_prefix("imported-")
            .is_some_and(|s| !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit()))
            || pending.sources.iter().any(|p| {
                !p.is_absolute()
                    || !p
                        .file_name()
                        .and_then(|s| s.to_str())
                        .is_some_and(|name| NAMES.contains(&name))
            })
        {
            return Err(error(
                "invalid import intent; source paths and suffix must be generated by the importer",
            ));
        }
        pending.sources.clone()
    } else {
        let mut sources = Vec::new();
        for name in NAMES {
            if let Some(path) =
                crate::catalog_journal::legacy_shared_path(dir, name).map_err(error)?
            {
                sources.push(path);
            }
        }
        sources
    };
    if sources.is_empty() {
        return Ok(());
    }
    let (local_groups, local_members) = groups.catalog_all()?;
    if pending.is_none()
        && (!flows.catalog_all()?.is_empty()
            || !queues.catalog_all()?.is_empty()
            || !local_groups.is_empty()
            || !local_members.is_empty()
            || !deleted(&dir.join("catalog-tombstones.json"))?.is_empty())
    {
        tracing::warn!("PRIVATE AND LEGACY SHARED CATALOGS BOTH EXIST: using private registries without merging; shared sources are untouched");
        return Ok(());
    }
    let mut locks = Vec::new();
    for source in &sources {
        locks.push(
            broker_storage::FileLock::try_exclusive(source).map_err(|e| {
                error(format!(
                    "{} is in use; stop the shared catalog owner before retrying: {e}",
                    source.display()
                ))
            })?,
        );
    }
    let mut pending = pending.unwrap_or_else(|| Import {
        sources,
        suffix: format!("imported-{}", chrono::Utc::now().timestamp_millis()),
        copied: false,
    });
    let persist = |pending: &Import| -> Result<(), BrokerError> {
        broker_storage::atomic_write_file(&marker, &serde_json::to_vec(pending).map_err(error)?)
            .map_err(error)?;
        std::fs::File::open(dir)
            .and_then(|f| f.sync_all())
            .map_err(error)
    };
    if !pending.copied {
        // Persist intent before touching any private registry, so a crash after
        // the first copy resumes rather than misclassifying it as user data.
        persist(&pending)?;
        let source = |name: &str| {
            pending
                .sources
                .iter()
                .find(|path| path.file_name().is_some_and(|file| file == name))
                .cloned()
        };
        let mut flow_rows = source("flows.json")
            .map(FlowProfileRegistry::read_snapshot_at)
            .transpose()?
            .unwrap_or_default();
        let mut queue_rows = source("subscriptions.json")
            .map(SubscriptionRegistry::read_snapshot_at)
            .transpose()?
            .unwrap_or_default();
        let (mut group_rows, mut member_rows) = source("groups.json")
            .map(GroupRegistry::read_snapshot_at)
            .transpose()?
            .unwrap_or_default();
        if let Some(path) = source("catalog-tombstones.json") {
            let removed = deleted(&path)?;
            flow_rows.retain(|row| !removed.contains(&row.id));
            queue_rows.retain(|row| !removed.contains(&row.id));
            group_rows.retain(|row| !removed.contains(&row.id));
            member_rows
                .retain(|row| !removed.contains(&row.id) && !removed.contains(&row.group_id));
            broker_storage::atomic_write_file(
                &dir.join("catalog-tombstones.json"),
                &std::fs::read(path).map_err(error)?,
            )
            .map_err(error)?;
        }
        let counts = (
            flow_rows.len(),
            queue_rows.len(),
            group_rows.len(),
            member_rows.len(),
        );
        flows.import_snapshot(flow_rows)?;
        queues.import_snapshot(queue_rows)?;
        groups.import_snapshot(group_rows, member_rows)?;
        std::fs::File::open(dir)
            .and_then(|f| f.sync_all())
            .map_err(error)?;
        pending.copied = true;
        persist(&pending)?;
        tracing::info!(
            flows = counts.0,
            queues = counts.1,
            groups = counts.2,
            members = counts.3,
            "imported legacy shared catalog into private registries"
        );
    }
    for source in &pending.sources {
        for path in [source.clone(), source.with_extension("journal")] {
            if path.exists() {
                std::fs::rename(
                    &path,
                    PathBuf::from(format!("{}.{}", path.display(), pending.suffix)),
                )
                .map_err(error)?;
            }
        }
        if let Some(parent) = source.parent() {
            std::fs::File::open(parent)
                .and_then(|f| f.sync_all())
                .map_err(error)?;
        }
    }
    std::fs::remove_file(marker).map_err(error)?;
    std::fs::File::open(dir)
        .and_then(|f| f.sync_all())
        .map_err(error)?;
    drop(locks);
    Ok(())
}
